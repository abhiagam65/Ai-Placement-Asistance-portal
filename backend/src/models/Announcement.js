import mongoose from 'mongoose';

const announcementSchema = new mongoose.Schema({
  title: {
    type: String,
    required: true,
    trim: true
  },
  content: {
    type: String,
    required: true
  },
  type: {
    type: String,
    enum: ['Placement Drive', 'Urgent Notice', 'Company Visit', 'Preparation Tip', 'General'],
    default: 'General'
  },
  companyName: {
    type: String,
    default: ''
  },
  isPinned: {
    type: Boolean,
    default: false
  },
  createdBy: {
    type: mongoose.Schema.Types.ObjectId,
    ref: 'User'
  }
}, {
  timestamps: true
});

export default mongoose.model('Announcement', announcementSchema);
